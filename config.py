# config.py

# ================= ШКАЛЫ И ОЦЕНКИ =================
# FORM_GAIN: усиление формы. При 1.5 герой с WR 65% (сглаженный ~63%), KDA 5+,
# максимальным pick rate и 20+ эффективных игр получает form_score около 0.76.
FORM_GAIN = 1.5
# COUNTER_SCALE / SYNERGY_SCALE: draft_score = sigmoid(преимущество / SCALE).
# +3 п.п. -> 0.73, +2 п.п. -> 0.66, +1 п.п. -> 0.58.
# КАК ПОДБИРАТЬ: запусти CLI с --debug и посмотри долю формы и драфта.
# Драфт даёт слишком много (например 85%) -> увеличь SCALE (0.04-0.05) или FORM_GAIN.
COUNTER_SCALE = 0.05
SYNERGY_SCALE = 0.05

# --- Сглаживание матчапов и синергии (байесовское, к среднему WR героя) ---
# Реальные матчап-эффекты обычно в пределах ±2-3 п.п. (std ~0.025). Для такого prior'а
# вес prior в «виртуальных играх» = 0.25 / 0.025^2 = 400, берём чуть мягче.
# Пример: матчап в 36 игр с сырым +11 п.п. после сглаживания даёт около +1 п.п.
MATCHUP_PRIOR_GAMES = 300
SYNERGY_PRIOR_GAMES = 300
# Учёт общей силы героя: ожидаемый WR = средний WR героя + поправка матчапа.
# 1.0 = полностью (рекомендуется), 0.0 = только «контрпик относительно среднего».
BASE_STRENGTH_WEIGHT = 1.0

# Пороги для текстовых пояснений (подбирать по --debug)
EXCELLENT_FORM_THRESHOLD = 0.65   # form_score, начиная с которого пишем «отличная форма»
STRONG_COUNTER_ADV = 0.01         # поправка матчапа (1 п.п. ПОСЛЕ сглаживания) для «силен/слаб против»

# Личный пул (режим «только мои герои»): герой попадает в выдачу, только если его form_score не ниже порога.
# 0.5 = нейтраль; 0.48 отсекает героев с явно плохой недавней формой (низкий WR и плохой KDA).
POOL_MIN_FORM = 0.48

# Нейтральные «средние» значения для абсолютной формы
RAW_NEUTRAL_WR = 0.50
RAW_NEUTRAL_KDA = 3.0
RAW_NEUTRAL_PR = 0.50

# Веса итоговой оценки (целевое распределение 40/60)
WEIGHT_FORM = 0.4
WEIGHT_DRAFT = 0.6
DRAFT_COUNTER_RATIO = 0.7
DRAFT_SYNERGY_RATIO = 0.3
# Неполный драфт: вес контрпика растёт с долей известных врагов (n/5), вес синергии с долей известных союзников (n/4).
# Если известно мало врагов и больше союзников, совет опирается в основном на синергию.
# Позиции союзников: если ты керри/мид (1-2), синергия с саппортами (4-5) весит больше, и наоборот.
SYNERGY_SUPPORT_BOOST = 1.5
MIN_ENEMIES_FOR_FULL_COUNTER = 4   # меньше известных врагов: предупреждение «драфт неполный»

# ================= СГЛАЖИВАНИЕ И ФИЛЬТРЫ =================
PRIOR_MATCHES = 5               # виртуальные игры для сглаживания WR формы
MIN_MATCHUP_GAMES = 50          # меньше этого числа игр в матчапе: предупреждение, без текста «сильный контрпик»
SHRINK_K = 10                   # шринкидж формы к 0.5 при малом числе игр
HALF_LIFE_DAYS = 30.0           # полураспад веса матча (дни)

# ================= API И ЗАПРОСЫ =================
# STRATZ matchUp. Схема ПРОВЕРЕНА в GraphQL Explorer: аргументы heroId, take, skip, bracketBasicIds, week, matchLimit...;
# поля with/vs { heroId2 matchCount winCount }; ответ matchUp приходит СПИСКОМ из одного элемента.
# winCount в vs = победы ЗАПРОШЕННОГО героя против heroId2 (проверено на Anti-Mage vs Medusa: 66.7%).
STRATZ_BRACKETS = "DIVINE_IMMORTAL"   # ранги данных (как «7k+» на Протрекере); можно "LEGEND_ANCIENT,DIVINE_IMMORTAL"
STRATZ_TAKE = 150                      # сколько героев возвращать (по умолчанию Stratz отдаёт только 10)
STRATZ_MATCHUP_QUERY = """
{
  heroStats {
    matchUp(heroId: %(hero_id)d, take: %(take)d, bracketBasicIds: [%(brackets)s]) {
      with { heroId2 matchCount winCount }
      vs { heroId2 matchCount winCount }
    }
  }
}
"""
STRATZ_TIMEOUT = 20
# Базовый WR героя для высоких рангов берём из OpenDota heroStats (бракеты 7=Divine, 8=Immortal)
HIGH_BRACKETS = (7, 8)
MIN_HIGH_BASE_PICKS = 300              # меньше пиков в высоких бракетах -> используем средний WR по всем рангам
CACHE_TTL = 86400
